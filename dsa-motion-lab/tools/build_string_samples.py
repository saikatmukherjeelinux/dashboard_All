"""Regenerate browser Python samples from the tested source of truth.

Run from the project root: python tools/build_string_samples.py
"""
import ast
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
source = (ROOT / 'python_examples' / 'strings.py').read_text(encoding='utf-8')
tree = ast.parse(source)
functions = {node.name: ast.get_source_segment(source, node)
             for node in tree.body if isinstance(node, ast.FunctionDef)}
examples = {
    'zstring': ('z_search', ['ABABABA', 'ABA']),
    'rabin': ('rabin_karp', ['ABABABA', 'ABA']),
    'horspool': ('horspool_search', ['HERE IS A SIMPLE EXAMPLE', 'EXAMPLE']),
    'aho': ('aho_corasick', ['ushers', ['he', 'she', 'his', 'hers']]),
    'trie': ('trie_autocomplete', ['ca', ['car', 'card', 'care', 'cat', 'dog']]),
    'suffix': ('suffix_array', ['banana']),
    'kasai': ('kasai_lcp', ['banana']),
    'manacher': ('manacher', ['babad']),
    'lcs': ('longest_common_subsequence', ['ABCBDAB', 'BDCABA']),
    'lcsubstr': ('longest_common_substring', ['ABABC', 'BABCA']),
    'edit': ('edit_distance', ['kitten', 'sitting']),
    'scs': ('shortest_common_supersequence', ['abac', 'cab']),
    'lps': ('longest_palindromic_subsequence', ['bbbab']),
    'palcut': ('palindrome_min_cuts', ['aab']),
    'wordbreak': ('word_break', ['leetcode', ['leet', 'code', 'lee']]),
    'distinct': ('count_subsequences', ['rabbbit', 'rabbit']),
    'wildcard': ('wildcard_match', ['adceb', '*a*b']),
    'minwindow': ('minimum_window', ['ADOBECODEBANC', 'ABC']),
    'anagrams': ('anagram_windows', ['cbaebabacd', 'abc']),
    'unique': ('longest_unique_substring', ['abcabcbb']),
}
dependencies = {'kasai': ['suffix_array'], 'lcs': ['_lcs_table'], 'scs': ['_lcs_table']}
samples = {}
for lesson, (name, args) in examples.items():
    pieces = ['from collections import Counter, deque']
    pieces.extend(functions[dependency] for dependency in dependencies.get(lesson, []))
    pieces.append(functions[name])
    pieces.append(f"print({name}({', '.join(repr(arg) for arg in args)}))")
    samples[lesson] = '\n\n'.join(pieces)
output = '// Generated by tools/build_string_samples.py; edit python_examples/strings.py.\n'
output += 'Object.assign(PY, ' + json.dumps(samples, ensure_ascii=False, indent=2) + ');\n'
(ROOT / 'assets' / 'string-python.js').write_text(output, encoding='utf-8')
print(f'Generated {len(samples)} standalone Python examples')
