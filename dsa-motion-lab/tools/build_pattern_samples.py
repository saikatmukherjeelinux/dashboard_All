"""Generate standalone samples from tested reference functions and catalogue JSON."""
import ast
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
source = (ROOT / 'python_examples/interview_patterns.py').read_text(encoding='utf-8')
functions = {node.name: ast.get_source_segment(source, node) for node in ast.parse(source).body if isinstance(node, ast.FunctionDef)}
names = dict(zip(
    ['two_sum', 'three_sum', 'product_except', 'sum_k', 'consecutive', 'rain', 'container', 'dutch', 'rotated', 'merge_intervals', 'meeting_rooms', 'top_k', 'quickselect', 'next_greater', 'window_max', 'jump', 'gas_station', 'robber', 'partition', 'knapsack', 'subsets', 'permutations', 'combination', 'queens', 'islands', 'union_find', 'fenwick'],
    ['two_sum', 'three_sum', 'product_except_self', 'subarray_sum_k', 'longest_consecutive', 'trapped_water', 'container_area', 'dutch_flag', 'rotated_search', 'merge_intervals', 'meeting_rooms', 'top_k_frequent', 'kth_largest', 'next_greater', 'window_maximum', 'jump_game', 'gas_station', 'house_robber', 'equal_partition', 'knapsack', 'subsets', 'permutations', 'combination_sum', 'n_queens', 'number_of_islands', 'connected_components', 'fenwick_ranges']))
catalog = json.loads((ROOT / 'python_examples/pattern_recipes.json').read_text(encoding='utf-8'))
samples = {}
for lesson in catalog:
    name = names[lesson['id']]
    args = ', '.join(f'{key}={value!r}' for key, value in lesson['defaults'].items())
    samples[lesson['id']] = 'from collections import Counter, deque\nimport heapq\n\n\n' + functions[name] + f'\n\nprint({name}({args}))\n'
(ROOT / 'assets/pattern-python.js').write_text('// Generated by tools/build_pattern_samples.py.\nObject.assign(PY, ' + json.dumps(samples, ensure_ascii=False, indent=2) + ');\n', encoding='utf-8')
(ROOT / 'python_examples/pattern_names.json').write_text(json.dumps(names, indent=2) + '\n', encoding='utf-8')
print(f'Generated {len(samples)} standalone interview algorithm samples')
