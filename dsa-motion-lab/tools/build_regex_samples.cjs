// Run from the project root: node tools/build_regex_samples.cjs
const fs=require('fs'),path=require('path');
const root=path.resolve(__dirname,'..');
const catalog=require('../assets/regex-catalog.js');
const reference=fs.readFileSync(path.join(root,'python_examples/regex_algorithms.py'),'utf8');
const samples={};
for(const recipe of catalog){
 const args=[...recipe.defaults,recipe.mode,recipe.flags,recipe.replacement].map(value=>JSON.stringify(value)).join(', ');
 samples[recipe.id]=`# ${recipe.title}\n# Python re syntax applies; JavaScript regex Unicode rules can differ.\n`+reference+`\n\nprint(regex_recipe(${args}))\n`;
}
fs.writeFileSync(path.join(root,'assets/regex-python.js'),'// Generated by tools/build_regex_samples.cjs from tested Python source.\nObject.assign(PY, '+JSON.stringify(samples,null,2)+');\n');
fs.writeFileSync(path.join(root,'python_examples/regex_recipes.json'),JSON.stringify(catalog.map(({id,title,defaults,mode,flags,replacement})=>({id,title,text:defaults[0],pattern:defaults[1],mode,flags,replacement})),null,2)+'\n');
console.log(`Generated ${catalog.length} runnable regex examples`);
