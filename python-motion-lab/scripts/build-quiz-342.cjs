// Build the additional bank from distinct worked examples and authored concepts.
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..'),context={window:{}};vm.createContext(context);
for(const file of ['lessons','quizzes','quizzes-more'])vm.runInContext(fs.readFileSync(path.join(root,`assets/${file}.js`),'utf8'),context);
const {LESSONS:lessons,QUIZZES:existing}=context.window,questions=[],used=new Set(existing.filter(q=>q.code).map(q=>q.code.trim()));
function alternatives(output){
 const values=[],put=value=>{if(value.trim()&&value!==output&&!values.includes(value))values.push(value);};
 // Plausible mistakes: opposite booleans, off-by-one results, missing or reversed
 // output lines, and repr/type confusion. Never use a second correct choice.
 if(/\b(?:True|False)\b/.test(output))put(output.replace(/\b(True|False)\b/g,x=>x==='True'?'False':'True'));
 if(/-?\d+/.test(output)){
  put(output.replace(/-?\d+/,x=>String(Number(x)+1)));
  put(output.replace(/-?\d+/,x=>String(Number(x)-1)));
 }
 const lines=output.split('\n');if(lines.length>1){put([...lines].reverse().join('\n'));put(lines.slice(0,-1).join('\n'));put(lines.slice(1).join('\n'));}
 if(output.includes('['))put(output.replace('[','(').replace(/\](?![\s\S]*\])/ ,')'));
 if(output.includes('None'))put(output.replace(/None/g,'False'));
 if(output.includes("'"))put(output.replace(/'/g,''));
 put('No output');put('TypeError');put('None');put('StopIteration');
 return values.slice(0,3);
}
for(const lesson of lessons.filter(l=>l.id<=155))for(const example of lesson.examples){
 if(used.has(example.code.trim()))continue;used.add(example.code.trim());
 questions.push({lesson:lesson.id,category:lesson.category,question:`What does this program print? ${lesson.label}: ${example.title}.`,code:example.code,format:'output',options:[example.output,...alternatives(example.output)],answer:0,explanation:example.explanation.join(' ')});
}
assert.equal(questions.length,274,'Distinct examples not already present in the quiz');
const rows=fs.readFileSync(path.join(root,'content/quiz-342-concepts.txt'),'utf8').trim().split(/\r?\n/);
assert.equal(rows.length,68);
for(const row of rows){
 const fields=row.split('|');assert.equal(fields.length,7,row);
 const [id,question,correct,a,b,c,explanation]=fields,lesson=lessons.find(l=>l.id===Number(id));assert(lesson,id);
 questions.push({lesson:lesson.id,category:lesson.category,question,options:[correct,a,b,c],answer:0,explanation});
}
const bank=questions.map((q,i)=>({...q,id:`q${159+i}`,collection:'new-342'}));
assert.equal(bank.length,342);const stems=new Set(existing.map(q=>q.question));
for(const q of bank){assert(!stems.has(q.question),q.question);stems.add(q.question);assert.equal(new Set(q.options).size,4,q.question);assert(q.options.every(x=>x.trim()));assert(q.explanation.length>70,q.question);}
fs.writeFileSync(path.join(root,'assets/quizzes-342.js'),'/* Generated by scripts/build-quiz-342.cjs. IDs q159–q500; 274 output and 68 conceptual questions. */\nwindow.QUIZZES.push(...'+JSON.stringify(bank,null,2)+');\n');
console.log('Built 342 new questions: 274 unique programs and 68 conceptual questions.');
